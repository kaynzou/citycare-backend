def ancestor(units_by_id, ward_id, level):
    order = {"WARD": "ward", "SDM": "sdm", "DISTRICT": "district", "STATE": "state", "COUNTRY": "country"}
    u = units_by_id[ward_id]
    while u["type"] != order[level]:
        u = units_by_id[u["parent"]]
    return u["id"]


def open_status(level, start):
    elapsed = -start
    if level == "WARD":
        return "PENDING" if elapsed < 0.5 * DAY else "VERIFIED" if elapsed < 1.6 * DAY else "IN_PROGRESS"
    return "ESCALATED" if elapsed < 2 * DAY else "IN_PROGRESS"


def simulate(rng, created, category, ward_id, units_by_id, profiles):
    sla = CATEGORY_SLA_DAYS[category] * DAY
    assignments, resolution, confirmation, confirmation_at = [], 0, 0, 0
    reopened, level_idx, start, status = 0, 0, created, None
    while True:
        level = ESCALATION_CHAIN[level_idx]
        prof = profiles[ancestor(units_by_id, ward_id, level)]
        deadline = start + sla
        if rng.random() < prof.diligence_at(start):
            used = clamp(prof.speed * (0.35 + 1.3 * rng.random()), 0.03, 0.96)
            t_res = start + round(sla * used)
            if t_res > 0:
                assignments.append([level, start, None, None])
                status = open_status(level, start)
                break
            evidence = rng.random() < (0.95 if reopened else prof.evidence)
            confirm_p, dispute_p = prof.reaction(evidence)
            if reopened:
                dispute_p = 0.0
            r = rng.random()
            t_react = t_res + round(rng.uniform(0.3, 4.0) * DAY)
            if r < dispute_p and t_react <= 0:
                assignments.append([level, start, "REOPENED", t_react, [t_res, int(evidence)]])
                reopened = 1
                start = t_react
                continue
            assignments.append([level, start, "RESOLVED", t_res])
            resolution = [t_res, level, int(evidence)]
            if dispute_p <= r < dispute_p + confirm_p and t_react <= 0:
                confirmation, confirmation_at = 1, t_react
            status = "RESOLVED"
            break
        if deadline > 0 or level_idx == len(ESCALATION_CHAIN) - 1:
            assignments.append([level, start, None, None])
            status = open_status(level, start)
            break
        assignments.append([level, start, "ESCALATED", deadline])
        level_idx += 1
        start = deadline
    return assignments, resolution, confirmation, confirmation_at, reopened, status


