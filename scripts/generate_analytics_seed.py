def clamp(x, lo, hi):
    return max(lo, min(hi, x))


class Profile:
    """How one authority behaves when a complaint is in its hands."""

    def __init__(self, diligence, trend=0.0, speed=0.5, evidence=0.9, gaming=False):
        self.diligence = diligence
        self.trend = trend      # change in diligence across the horizon (improving > 0)
        self.speed = speed      # typical fraction of the SLA window used
        self.evidence = evidence
        self.gaming = gaming

    def diligence_at(self, start_min):
        progress = clamp(1 + start_min / (HORIZON_DAYS * DAY), 0, 1)  # 0 = oldest, 1 = now
        return clamp(self.diligence + self.trend * (progress - 0.5), 0.2, 0.97)

    def reaction(self, evidence):
        """(confirm probability, dispute probability) for the citizen's response."""
        if self.gaming:
            return (0.40, 0.22) if evidence else (0.18, 0.47)
        return (0.62, 0.05) if evidence else (0.45, 0.25)


