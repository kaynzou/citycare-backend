def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--copy-to", help="also copy the file into this directory (the prototype's analytics folder)")
    args = ap.parse_args()

    rng = random.Random(20260927)
    units, authorities, profiles = build_units(rng)
    units_by_id = {u["id"]: u for u in units}
    wards = [u for u in units if u["type"] == "ward"]
    cats, weights = zip(*CATEGORY_WEIGHTS)

    complaints = handcrafted()
    taken = {c[0] for c in complaints}
    serial = 30001
    for w in wards:
        volume = {"ward42": 34, "ward24": 30, "ward30": 28, "ward7": 28, "ward15": 36, "ward17": 26}.get(w["id"], rng.randint(18, 30))
        for _ in range(volume):
            created = -round(HORIZON_DAYS * DAY * (rng.random() ** 1.12)) - 30
            category = rng.choices(cats, weights)[0]
            template = rng.choice(TITLES[category])
            title = template.format(s=rng.choice(STREETS), l=rng.choice(LANDMARKS))
            title = title[0].upper() + title[1:]
            severity = clamp(BASE_SEVERITY.get(category, 2) + rng.choice([-1, 0, 0, 1]), 1, 5)
            upvotes = severity * rng.randint(1, 24)
            cv = rng.random() < 0.75
            gv = cv and rng.random() < 0.85 and created < -DAY
            asg, res, conf, conf_at, reop, status = simulate(rng, created, category, w["id"], units_by_id, profiles)
            while f"CMP{serial}" in taken:
                serial += 1
            cid = f"CMP{serial}"
            serial += 1
            complaints.append([cid, category, title, w["id"], severity, upvotes, (1 if cv else 0) | (2 if gv else 0),
                               created, status, asg, res, conf, conf_at, reop])

    data = {
        "schema": 1,
        "note": ("Demo dataset for the CivicConnect analytics prototype, generated by "
                 "scripts/generate_analytics_seed.py (seeded RNG, reproducible). Times are minutes relative "
                 "to the moment the data is loaded (negative = past). No metric is stored here - the analytics "
                 "engine derives everything from these complaint records."),
        "complaint_fields": ["id", "category", "title", "ward_id", "severity", "upvotes", "flags", "created",
                             "status", "assignments", "resolution", "confirmation", "confirmation_at", "reopen_count"],
        "flag_bits": {"community_verified": 1, "gov_verified": 2, "reported_by_demo_citizen": 4},
        "assignment_fields": ["level", "start", "outcome", "outcome_at", "[closed_at, evidence] when REOPENED"],
        "resolution_fields": ["at", "level", "evidence"],
        "units": units,
        "authorities": authorities,
        "descriptions": DESCRIPTIONS,
        "complaints": complaints,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        json.dump(data, f, separators=(",", ":"))
    size = os.path.getsize(OUT)
    print(f"wrote {OUT}: {len(units)} units, {len(authorities)} authorities, {len(complaints)} complaints, {size/1024:.0f} KB")
    if args.copy_to:
        # A script (not a .json fetch) so the prototype also works when opened as a local file.
        os.makedirs(args.copy_to, exist_ok=True)
        with open(OUT) as f, open(os.path.join(args.copy_to, "seed.js"), "w") as js:
            js.write(SEED_JS_PREFIX + f.read() + SEED_JS_SUFFIX)
        print(f"wrote {os.path.join(args.copy_to, 'seed.js')}")


if __name__ == "__main__":
    main()
